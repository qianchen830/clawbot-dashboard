def get_day_index(base_date_str, period=5):
    """计算从基准日期起的天数（决定主题循环）"""
    base = datetime.strptime(base_date_str, "%Y-%m-%d")
    today = datetime.now()
    return (today - base).days % period

def get_token():
    import requests
    resp = requests.post(
        "https://open.feishu.cn/open-apis/auth/v3/tenant_access_token/internal",
        json={"app_id": APP_ID, "app_secret": APP_SECRET},
        timeout=10
    )
    if resp.status_code == 200 and resp.json().get("code") == 0:
        return resp.json().get("tenant_access_token")
    return None

def build_content(topic_data):
    """将主题数据构建为飞书消息内容"""
    lines = []
    if "theme" in topic_data:
        lines.append(f"**专题**: {topic_data['theme']}  ")
    lines.append("")
    for p in topic_data["points"]:
        lines.append(f"• {p}")
    return "\n".join(lines)

def send_feishu(topic_data, hour, template="blue"):
    import requests
    token = get_token()
    if not token:
        print("获取token失败")
        return False

    category = topic_data.get("category", "学习")
    topic = topic_data["topic"]
    content = build_content(topic_data)

    title = f"📚 [{category}] {topic}"
    footer = f"精读时间：{datetime.now().strftime('%Y-%m-%d')} | {category}每日精读"

    card = {
        "receive_id": USER_ID,
        "msg_type": "interactive",
        "content": json.dumps({
            "config": {"wide_screen_mode": True},
            "header": {"title": {"tag": "plain_text", "content": title}, "template": template},
            "elements": [
                {"tag": "markdown", "content": content},
                {"tag": "markdown", "content": f"---  {footer}"}
            ]
        })
    }

    resp = requests.post(
        "https://open.feishu.cn/open-apis/im/v1/messages?receive_id_type=open_id",
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        json=card, timeout=15
    )
    if resp.status_code == 200:
        data = resp.json()
        if data.get("code") == 0:
            return True
        print(f"发送失败: {data.get('msg')}")
    else:
        print(f"请求失败: {resp.status_code}")
    return False

def save_note(topic_data, hour):
    now = datetime.now().strftime('%Y-%m-%d %H:%M')
    safe_topic = topic_data['topic'].replace('/', '-').replace(' ', '-')
    safe_category = topic_data['category'].replace('/', '-').replace(' ', '-')
    filename = f"{now}-{safe_category}-{safe_topic}.md"
    filepath = f"{WORKSPACE}/memory/{filename}"

    lines = [f"# {topic_data['topic']}", "", f"**时间**: {now}", f"**分类**: {topic_data['category']}", ""]
    for p in topic_data['points']:
        lines.append(f"- {p}")

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write("\n".join(lines))
    return filepath

