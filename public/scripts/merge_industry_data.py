# 构建新的EXTENDED_INDUSTRIES
new_extended = {}
for key, data in extracted_data.items():
    if key in ['solutions']:  # 跳过特殊文件
        continue
    
    industry_name = data['name']
    
    # 使用补充的信息
    scale = INDUSTRY_SCALES.get(industry_name, data['scale'])
    solutions = INDUSTRY_SOLUTIONS.get(industry_name, data['solutions'])
    results = INDUSTRY_RESULTS.get(industry_name, data['results'])
    
    # 清理痛点
    pain_points = []
    for pp in data['pain_points']:
        cleaned = pp.replace('**', '').replace('*', '').strip()
        if cleaned and len(cleaned) > 5:
            pain_points.append(cleaned)
    
    # 确保至少有3个痛点
    while len(pain_points) < 3:
        pain_points.append(f"{industry_name}管理复杂，需要数字化升级")
    pain_points = pain_points[:6]  # 最多6个
    
    new_extended[key] = {
        "name": industry_name,
        "icon": data['icon'],
        "scale": scale,
        "pain_points": pain_points,
        "solutions": solutions,
        "results": results
    }

print(f"生成了 {len(new_extended)} 个扩展行业数据")

# 保存为JSON
output_file = MEMORY_DIR / "extended_industries_new.json"
with open(output_file, 'w', encoding='utf-8') as f:
    json.dump(new_extended, f, ensure_ascii=False, indent=2)

print(f"新数据已保存到: {output_file}")

