def generate_document(doc_type, customer_info):
    """生成文档结构"""
    templates = {
        "survey_report": SURVEY_REPORT_TEMPLATE_V4,
        "blueprint": BLUEPRINT_TEMPLATE_V4,
        "uat": UAT_TEMPLATE_V4,
        "survey_questionnaire": SURVEY_QUESTIONNAIRE_V4
    }
    
    template = templates.get(doc_type, SURVEY_REPORT_TEMPLATE_V4)
    
    # 替换客户信息
    result = {
        "name": template["name"],
        "customer": customer_info.get("customer_name", "XX公司"),
        "project": customer_info.get("project_name", "ERP项目"),
        "sections": template["sections"]
    }
    
    return result

def save_document_json(doc, output_path):
    """保存文档为JSON文件"""
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
    return output_path

def print_document(doc):
    """打印文档结构"""
    print(f"\n{'='*60}")
    print(f"文档名称: {doc['name']}")
    print(f"客户: {doc['customer']}")
    print(f"项目: {doc['project']}")
    print(f"{'='*60}\n")
    
    for section in doc["sections"]:
        print(f"【{section['title']}】")
        for content in section["content"]:
            print(f"  {content['subtitle']}")
            for item in content["items"]:
                print(f"    - {item}")
        print()

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Word文档生成器V4")
    parser.add_argument("--type", choices=["survey_report", "blueprint", "uat", "survey_questionnaire"], 
                        default="survey_report", help="文档类型")
    parser.add_argument("--customer", default="XX公司", help="客户名称")
    parser.add_argument("--project", default="ERP项目", help="项目名称")
    parser.add_argument("--output", help="输出文件路径")
    
    args = parser.parse_args()
    
    customer_info = {
        "customer_name": args.customer,
        "project_name": args.project
    }
    
    doc = generate_document(args.type, customer_info)
    
    if args.output:
        save_document_json(doc, args.output)
        print(f"文档已保存到: {args.output}")
    else:
        print_document(doc)
