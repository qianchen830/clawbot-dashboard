def generate_outline(outline_type, customer_info):
    """生成PPT提纲"""
    outlines = {
        "presales": PRESALES_OUTLINE_V4,
        "kickoff": KICKOFF_OUTLINE_V4,
        "blueprint": BLUEPRINT_OUTLINE_V4,
        "golive": GOLIVE_OUTLINE_V4,
        "acceptance": ACCEPTANCE_OUTLINE_V4,
        "uat": UAT_OUTLINE_V4,
        "survey": SURVEY_OUTLINE_V4
    }
    
    outline = outlines.get(outline_type, PRESALES_OUTLINE_V4)
    
    # 替换客户信息
    result = {
        "name": outline["name"],
        "customer": customer_info.get("customer_name", "XX公司"),
        "project": customer_info.get("project_name", "ERP项目"),
        "total_pages": outline["total_pages"],
        "chapters": outline["chapters"]
    }
    
    return result

def save_outline_json(outline, output_path):
    """保存提纲为JSON文件"""
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(outline, f, ensure_ascii=False, indent=2)
    return output_path

def print_outline(outline):
    """打印提纲"""
    print(f"\n{'='*60}")
    print(f"PPT提纲: {outline['name']}")
    print(f"客户: {outline['customer']}")
    print(f"项目: {outline['project']}")
    print(f"总页数: {outline['total_pages']}")
    print(f"{'='*60}\n")
    
    for chapter in outline["chapters"]:
        print(f"【{chapter['chapter']}】({chapter['pages']}页)")
        for section in chapter["sections"]:
            print(f"  - {section['title']}")
            for content in section['content']:
                print(f"      · {content}")
        print()

